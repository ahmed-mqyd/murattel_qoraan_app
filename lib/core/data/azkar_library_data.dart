/// مرجع آية داخل المصحف (رقم السورة + رقم الآية داخل السورة)
class AyahRef {
  final int surahId;
  final int ayahInSurah;
  const AyahRef(this.surahId, this.ayahInSurah);
}

/// نص ذكر واحد مع عدد التكرار والمصدر
class DhikrData {
  final String text;
  final int count;

  /// التخريج أو المرجع (اختياري)
  final String? source;

  const DhikrData(this.text, {this.count = 1, this.source});
}

/// مجموعات أقسام الأذكار — تتحكم في تبويب شريط الأقسام داخل المشغّل
enum AzkarGroup { daily, library, hisn }

class AzkarCategoryData {
  final String key;
  final String title;
  final String? subtitle;
  final IconData icon;
  final AzkarGroup group;
  final List<DhikrData> items;

  const AzkarCategoryData({
    required this.key,
    required this.title,
    this.subtitle,
    required this.icon,
    required this.group,
    required this.items,
  });
}

